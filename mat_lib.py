import re

# --- НАСТРОЙКИ ---
# Если False, то слово "нах" будет считаться матом. 
# Если True, то "нах" пропустит (ищем только явные корни).
STRICT_MODE = False 

# --- СПИСКИ ---
# Слова-исключения (Белый список), которые содержат корни мата, но матом не являются
WHITELIST = {
    'хлеб', 'употреб', 'треб', 'греб', 'колеб', 'оскорб', 'рубл', 'корабл',
    'истреб', 'реб', 'скреб', 'углуб', 'парикмахер', 'херсон', 'страх', 'трах',
    'сабля', 'ансамбля', 'граблей', 'рублей', 'стебля', 'оглобля', 'люб', 'влюб'
}

# Основные паттерны (корни зла)
# Мы используем подмену символов, чтобы ловить написание через латиницу (xуй, eбaть и т.д.)
PATTERNS = [
    r'х[уy]([ийяёeю]|ли|лe|лi|лu)',          # ху.
    r'п[иeё]зд',                             # п.зд
    r'[её]б[ауеио](?!(л\b|н\b|с\b))',       # еб. (с проверкой, чтобы не банить ебел/ебен)
    r'[её]б[лltw]',                          # ебл
    r'бл[яy](?!(х\b|ш\b))',                  # бля (кроме блях, бляш)
    r'м[уy]д[аио]',                          # муд
    r'г[ао]ндон',                            # г.ндон
    r'с[уy]ч[аик]',                          # суч.
    r'с[уy]к[аи]',                           # сук.
    r'з[ао]л[уy]п',                          # з.луп
    r'м[ао]нд[аиу]',                         # м.нд
    r'п[иe]д[аоэe]р',                        # п.д.р
    r'д[ао]лб[ао]ё',                         # д.лб.
    r'г[ао]вн',                              # г.вн
    r'д[еe]рьм',                             # д.рьм
    r'ж[оo]п',                               # ж.п
    r'ц[еe]лк',                              # ц.лк
    r'чм[оэe]'                               # чм.
]

# Компилируем регулярку один раз для скорости
COMPILED_PATTERN = re.compile(r'|'.join(PATTERNS), re.IGNORECASE | re.UNICODE)

def check_text(text):
    """
    Возвращает True, если найден мат.
    """
    if not text: return False
    
    # 1. Нормализация: убираем лишние символы, чтобы "х.у.й" стало "хуй"
    # Оставляем только буквы (рус + англ) и пробелы
    clean_text = re.sub(r'[^a-zA-Zа-яА-ЯёЁ\s]', '', text)
    
    # Разбиваем на слова
    words = clean_text.split()
    
    for word in words:
        word_lower = word.lower()
        
        # 2. Проверка белого списка (сразу пропускаем хорошие слова)
        is_safe = False
        for safe_word in WHITELIST:
            if safe_word in word_lower:
                is_safe = True
                break
        if is_safe: continue

        # 3. Поиск мата
        if COMPILED_PATTERN.search(word_lower):
            # Доп. проверка для коротких слов, чтобы не банить лишнее
            if len(word_lower) < 3: continue
            return True
            
    return False